<div class="col-sm-7">
  <p>株式会社アセットデザインラボ（アセラボ）は、特定の金融機関には属さず、金融商品の販売も行わない、中立・独立のファイナンシャルプランナー（FP）事務所です。</p><p>弊社は、日本経済を支えている中小企業で働く皆さまの資産形成を強力にサポートしていきたい、と考えています。</p><p>現在、「NISA」や「個人型確定拠出年金（iDeCoイデコ）」という税制優遇のある資産形成制度が注目されています。これらの制度の中心となっている金融商品は投資信託です。</p>
<p>弊社は、長年、投資信託業界に身を置いてきたFPである資産形成アドバイザーが、投資信託が中心となっている制度の仕組みや、資産形成のの手段である資産運用の基本などについて、「金融経済教育」において丁寧かつ詳しく解説してまいります。</p>
