    <h3 class="text-center">アセットデザインラボの役割</h3>
		<p class="h5"><strong>中小企業で働く方々に金融経済教育をお届けすること！</strong></p>
<p  class="h5"><strong>それがアセットデザインラボの大きな役割の１つです。</strong></p>
<p>大企業に比べ、給与水準。退職金制度、企業年金制度など必ずしも十分とはいえない、中小企業で働く皆さまが、
 ご自身で、ライフイベントや老後のための資産形成を行えるように、少しでもお力になりたいと考えています。</p>
<p>Z世代と呼ばれる学生が、会社選びの際にあったら良いと思う研修の１つが「資産形成・金融リテラシー研修」です。</p>
<p>また、企業型確定拠出年金）企業型DC）を導入している企業では、制度加入時教育、継続投資教育を通じて、社員（加入者）の金融リテラシ－向上に努めています。</p>
<p>しかしながら、企業型DCを導入していない企業で働く社員は、このような金融経済教育を受ける機会が少ないのが現状です。</p>
<p>アセットデザインラボは、中小企業の経営者をはじめ、社員の皆さま方の金融リテラシー向上をお手伝いし、将来の夢の実現や老後の安心確保のために、「金融経済教育」を通じてお役に立ちたいと考えています。</p>
<p>福利厚生制度としての「社員向け金融経済教育」を通じて、人材採用や社員満足度向上に寄与し、皆さまのファイナンシャル・ウェルビーイングの実現をサポートいたします。</p>

